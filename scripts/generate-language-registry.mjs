// Writes src/lib/language-registry.json from Legesher's language registry.
//
// The registry is `libs/i18n/legesher_i18n/languages.json` in legesher/legesher.
// The site keeps only what its pages read: each language's code, its BCP 47
// tag, its writing direction, whether its script has letter case, and its pack
// status. Run it again whenever the registry changes, alongside regenerating
// src/lib/pack-samples.json, and commit both.
//
// Usage: node scripts/generate-language-registry.mjs <path to languages.json>

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/generate-language-registry.mjs <path to languages.json>');
  process.exit(2);
}

const registry = JSON.parse(readFileSync(source, 'utf-8'));
const required = ['bcp47', 'rtl', 'has_case_distinction', 'status'];

const languages = Object.entries(registry.languages)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([code, entry]) => {
    for (const field of required) {
      if (!(field in entry)) throw new Error(`Registry entry ${code} has no ${field}`);
    }
    return {
      code,
      tag: entry.bcp47,
      rtl: entry.rtl,
      case: entry.has_case_distinction,
      status: entry.status,
    };
  });

const out = {
  _comment:
    'Generated by scripts/generate-language-registry.mjs from legesher_i18n/languages.json in legesher/legesher. Regenerate, do not edit by hand.',
  canonical: registry.canonical_language,
  languages,
};

const target = join(import.meta.dirname, '..', 'src', 'lib', 'language-registry.json');
writeFileSync(target, JSON.stringify(out, null, 2) + '\n');
console.log(`Wrote ${languages.length} languages to ${target}`);
